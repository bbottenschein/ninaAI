"use server";

import { redirect } from "next/navigation";
import { createClient } from "@/lib/supabase/server";

// Die E-Mail wird zurückgegeben, weil React das Formular nach dem Absenden
// zurücksetzt – so muss sie nach einem Tippfehler nicht neu eingegeben werden.
export type LoginState = { error?: string; email?: string };

export async function login(
  _prev: LoginState,
  formData: FormData,
): Promise<LoginState> {
  const email = String(formData.get("email") ?? "").trim();
  const password = String(formData.get("password") ?? "");

  if (!email || !password) {
    return { error: "Bitte E-Mail und Passwort eingeben.", email };
  }

  const supabase = await createClient();
  const { error } = await supabase.auth.signInWithPassword({ email, password });

  if (error) {
    return { error: "E-Mail oder Passwort stimmt nicht.", email };
  }

  redirect("/");
}

export async function logout() {
  const supabase = await createClient();
  await supabase.auth.signOut();
  redirect("/login");
}
